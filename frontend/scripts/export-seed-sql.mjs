#!/usr/bin/env node
/**
 * Generates seed SQL from content/portfolio.json — the same source the
 * content scripts push from, so the seed can never disagree with the site.
 *
 *   npm run content:seed        (writes supabase/seed.sql)
 *
 * Only needed for a fresh Supabase project. For day-to-day changes use
 * `npm run content:push`, which diffs first.
 */
import { loadContent, toRows } from './lib/content.mjs';

const rows = toRows(loadContent());

// Postgres dollar-quoting sidesteps escaping entirely for the HTML content
// blocks, which are full of both single and double quotes.
let tagCounter = 0;
const dollarQuote = (value) => {
  const tag = `seed_${tagCounter++}`;
  return `$${tag}$${value ?? ''}$${tag}$`;
};

const sqlString = (value) => `'${String(value ?? '').replace(/'/g, "''")}'`;

const sqlArray = (values) =>
  !values || values.length === 0
    ? `'{}'::text[]`
    : `ARRAY[${values.map(sqlString).join(', ')}]::text[]`;

const lines = [
  '-- Generated by scripts/export-seed-sql.mjs from content/portfolio.json.',
  '-- Do not hand-edit. Edit the JSON and re-run: npm run content:seed',
  '',
  'truncate public.projects, public.skills, public.journey;',
  '',
  'insert into public.projects (lens, name, status, description, content, skills, sort_order) values',
  rows.projects
    .map(
      (p) =>
        `  (${sqlString(p.lens)}, ${sqlString(p.name)}, ${sqlString(p.status)}, ${sqlString(p.description)}, ${dollarQuote(p.content)}, ${sqlArray(p.skills)}, ${p.sort_order})`,
    )
    .join(',\n') + ';',
  '',
  'insert into public.skills (lens, name, url, sort_order) values',
  rows.skills
    .map((s) => `  (${sqlString(s.lens)}, ${sqlString(s.name)}, ${sqlString(s.url)}, ${s.sort_order})`)
    .join(',\n') + ';',
  '',
  'insert into public.journey (type, type_label, title, organization, duration, logo, sort_order) values',
  rows.journey
    .map(
      (j) =>
        `  (${sqlString(j.type)}, ${sqlString(j.type_label)}, ${sqlString(j.title)}, ${sqlString(j.organization)}, ${sqlString(j.duration)}, ${sqlString(j.logo)}, ${j.sort_order})`,
    )
    .join(',\n') + ';',
  '',
];

console.log(lines.join('\n'));
